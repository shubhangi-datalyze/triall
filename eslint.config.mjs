import { dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { FlatCompat } from '@eslint/eslintrc';

/**
 * Flat config for ESLint 9.
 *
 * The repo had no config at all, so `npm run lint` dropped into next lint's
 * interactive setup and could never run in CI or non-interactively. This is the
 * standard Next.js rule set (core-web-vitals plus the TypeScript rules),
 * reached through FlatCompat because eslint-config-next still ships as eslintrc.
 */

const compat = new FlatCompat({
  baseDirectory: dirname(fileURLToPath(import.meta.url)),
});

export default [
  {
    ignores: [
      '.next/**',
      'node_modules/**',
      'public/**',
      // Generated by Next on every build.
      'next-env.d.ts',
      'lib/content/registry.generated.ts',
      'lib/data/*.generated.*',
      // The tracking agent is its own package with its own tsconfig and tests.
      'tracking-agent/**',
      '.datalyze/**',
      // Pravix is its own app (Vite + Express) with its own config and Vercel project.
      'pravix/**',
    ],
  },
  ...compat.extends('next/core-web-vitals', 'next/typescript'),
  {
    rules: {
      // A warning rather than an error, deliberately. next build runs ESLint
      // and fails on errors, and the repo already carries a dozen dead
      // constants (RICH_HINT and friends in lib/content/*). Turning this to
      // error would break the build on code this branch did not write, and
      // deleting someone else's dead code is not this branch's job. It still
      // shows up in `npm run lint`.
      '@typescript-eslint/no-unused-vars': [
        'warn',
        { argsIgnorePattern: '^_', varsIgnorePattern: '^_' },
      ],
    },
  },
];
